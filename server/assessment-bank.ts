/**
 * «بانک ارزیابی» — the content behind the test module.
 *
 * Honest framing, stated in the UI and in the docs: these are **structured
 * work-sample and situational-judgement items with an explicit scoring key**,
 * not a validated psychometric instrument. There is no norm group, no IQ claim
 * and no personality label. Every answer has a reason in the key, and the score
 * is only ever one input next to the résumé, the scorecard and the interview.
 */
import type { AssessmentKind, AssessmentOption } from '../src/types/assessment';

export interface BankQuestionSingle {
  id: string;
  type: 'single';
  text: string;
  hint?: string;
  options: (AssessmentOption & { score: number })[];
}

export interface BankQuestionScale {
  id: string;
  type: 'scale';
  text: string;
  dimension: string;
  /** A reverse-keyed statement: agreeing means the opposite of the label. */
  reverse?: boolean;
}

export type BankQuestion = BankQuestionSingle | BankQuestionScale;

export interface AssessmentTemplate {
  id: string;
  name: string;
  kind: AssessmentKind;
  summary: string;
  intro: string;
  durationMinutes: number;
  dimensions: { id: string; label: string }[];
  questions: BankQuestion[];
  /** How to read the result — this text is shown to HR, never to the candidate. */
  reading: string;
  scored: boolean;
}

/** Four answers per scenario, always with one clearly better line of action. */
function q(id: string, text: string, options: [string, number][], hint?: string): BankQuestionSingle {
  return {
    id,
    type: 'single',
    text,
    ...(hint ? { hint } : {}),
    options: options.map(([label, score], i) => ({ id: `${id}-${'abcd'[i]}`, label, score })),
  };
}

function s(id: string, text: string, dimension: string, reverse = false): BankQuestionScale {
  return { id, type: 'scale', text, dimension, ...(reverse ? { reverse } : {}) };
}

