/**
 * «کیت مصاحبه» — the question bank behind it.
 *
 * A generic question list is useless: the same «نقاط قوت و ضعفت چیست؟» for a
 * network engineer and a call-centre agent tells the interviewer nothing. So the
 * bank is organised by the work itself — one pack per competency, each question
 * paired with what a strong answer sounds like and what a thin one sounds like.
 *
 * The kit is then *composed* per job: the job's own criteria pick the packs, the
 * role title anchors the opening, and a chosen candidate adds questions built
 * from their résumé — the deep-review findings, the weak spots, the claims worth
 * checking. Nothing is stored: a job edited tomorrow gets a different kit.
 */
